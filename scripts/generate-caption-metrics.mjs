// Writes src/lib/domain/caption-metrics.ts: advance widths of the sticker caption
// font, so the sticker form and the PDF fit captions the same way.
// Run after changing the caption font:
// `node scripts/generate-caption-metrics.mjs && npx prettier --write src/lib/domain/caption-metrics.ts`.
import { writeFileSync } from 'node:fs';
import { openSync } from 'fontkit';

const FONT = 'assets/fonts/DejaVuSans.ttf';
const OUT = 'src/lib/domain/caption-metrics.ts';

const ranges = [
	[0x20, 0x7e], // ASCII
	[0xa0, 0xff], // Latin-1: «», °, ±, ×…
	[0x400, 0x45f], // Cyrillic
	[0x2010, 0x2026] // dashes, quotes, ellipsis
];
const extra = ['№', '€', '₽', '™', '−'];

const font = openSync(FONT);
const chars = [];
for (const [from, to] of ranges)
	for (let c = from; c <= to; c++) chars.push(String.fromCodePoint(c));
chars.push(...extra);

let text = '';
const widths = [];
let widest = 0;
for (const char of chars) {
	const glyph = font.glyphForCodePoint(char.codePointAt(0));
	if (!glyph || glyph.id === 0) continue;
	text += char;
	widths.push(glyph.advanceWidth);
	widest = Math.max(widest, glyph.advanceWidth);
}

const source = `// Generated by scripts/generate-caption-metrics.mjs from ${FONT}. Do not edit.

export const UNITS_PER_EM = ${font.unitsPerEm};
/** Width of characters missing from the table: the widest one, to never overflow. */
export const FALLBACK_WIDTH = ${widest};
export const CHARS = ${JSON.stringify(text)};
export const WIDTHS = [${widths.join(', ')}];
`;
writeFileSync(OUT, source);
console.log(`${OUT}: ${text.length} characters`);
